static const uint8_t SPI_6020_CAL[24] = {
    0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x40,
    0x00, 0x40, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x3B, 0x34, 0x3B, 0x34, 0x3B, 0x34
};

const spi_entry_t SPI_TABLE[] = {
    { 0x6010, 16, SPI_6010 },
    { 0x601B, 1, SPI_601B },
    { 0x6000, 16, SPI_6000 },
    { 0x6050, 13, spi_color_6050 },
    { 0x6080, 24, SPI_6080 },
    { 0x6098, 18, SPI_6098 },
    { 0x603D, 25, SPI_603D },
    { 0x6020, 24, SPI_6020_CAL },
    { 0x8010, 24, SPI_FF   },
    { 0x8028, 24, SPI_FF   },
};

uint8_t const SPI_TABLE_N =
    (uint8_t)(sizeof(SPI_TABLE) / sizeof(SPI_TABLE[0]));

const spi_entry_t *spi_find(uint16_t addr) {
    uint8_t k;
    for (k = 0u; k < SPI_TABLE_N; k++) {
        if (SPI_TABLE[k].addr == addr) {
            return &SPI_TABLE[k];
        }
    }
    return NULL;
}

/* Joy-Con provisional zero-fill (see spi.h). Zeros ONLY, provisional. */
static const uint8_t SPI_JOY_BLANK[32] = {0};

const uint8_t *spi_joy_blank(uint8_t req_len, uint8_t *out_len) {
    if (out_len == NULL || req_len == 0u) {
        return NULL;
    }
    *out_len = req_len > 32u ? 32u : req_len;
    return SPI_JOY_BLANK;
}

